import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { assessPlan } from "../lib/assess";
import { evalScenarios } from "../lib/eval-scenarios";
import { planOffline } from "../lib/plan-offline";

type Row = {
  id: string;
  name: string;
  structure: boolean;
  kit: boolean;
  safety: boolean;
  language: boolean;
  safetyEdits: number;
  kitEdits: number;
  reasons: string[];
};

const started = Date.now();
const rows: Row[] = [];
const changeCounts = new Map<string, number>();

for (const scenario of evalScenarios) {
  try {
    const plan = planOffline(scenario.input);
    const report = assessPlan(plan, scenario.input);
    for (const change of plan.safetyChanges) {
      changeCounts.set(change.code, (changeCounts.get(change.code) ?? 0) + 1);
    }
    const reasons = [
      ...report.structure.reasons.map((reason) => `Structure: ${reason}`),
      ...report.kit.reasons.map((reason) => `Kit: ${reason}`),
      ...report.safety.reasons.map((reason) => `Safety: ${reason}`),
      ...report.language.reasons.map((reason) => `Language: ${reason}`),
    ];
    rows.push({
      id: scenario.id,
      name: scenario.name,
      structure: report.structure.ok,
      kit: report.kit.ok,
      safety: report.safety.ok,
      language: report.language.ok,
      safetyEdits: plan.safetyChanges.length,
      kitEdits: plan.kitAdjustments.length,
      reasons,
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : "Unknown error";
    rows.push({
      id: scenario.id,
      name: scenario.name,
      structure: false,
      kit: false,
      safety: false,
      language: false,
      safetyEdits: 0,
      kitEdits: 0,
      reasons: [`The planner threw: ${message}`],
    });
  }
}

const total = rows.length;
const count = (pick: (row: Row) => boolean) => rows.filter(pick).length;
const kitPass = count((row) => row.kit);
const safetyPass = count((row) => row.safety);
const structurePass = count((row) => row.structure);
const languagePass = count((row) => row.language);
const allPass = count(
  (row) => row.structure && row.kit && row.safety && row.language,
);
const failures = rows.filter((row) => row.reasons.length > 0);
const safetyEdits = rows.reduce((sum, row) => sum + row.safetyEdits, 0);
const elapsed = Date.now() - started;

const mark = (ok: boolean) => (ok ? "pass" : "fail");

const table = [
  "| Scenario | Structure | Kit | Safety | Language | Safety edits |",
  "| --- | --- | --- | --- | --- | --- |",
  ...rows.map(
    (row) =>
      `| ${row.id} | ${mark(row.structure)} | ${mark(row.kit)} | ${mark(row.safety)} | ${mark(row.language)} | ${row.safetyEdits} |`,
  ),
].join("\n");

const changeLines =
  changeCounts.size === 0
    ? "None."
    : [...changeCounts.entries()]
        .sort((a, b) => a[0].localeCompare(b[0]))
        .map(([code, times]) => `- ${code}: ${times}`)
        .join("\n");

const failureLines =
  failures.length === 0
    ? "None."
    : failures
        .map((row) => `### ${row.id}\n\n${row.reasons.map((reason) => `- ${reason}`).join("\n")}`)
        .join("\n\n");

const markdown = `# Evaluation

Generated by \`scripts/eval.ts\` at ${new Date().toISOString()}.
These numbers are the output of that run. Do not edit them by hand.

- Mode: offline planner (\`planOffline\`). The AI Gateway was not called.
- Runtime: Node ${process.version}
- Scenarios: ${total}
- Elapsed: ${elapsed} ms

## Summary

| Check | Passed | Total |
| --- | ---: | ---: |
| Plans produced | ${total - rows.filter((row) => row.reasons.some((reason) => reason.startsWith("The planner threw"))).length} | ${total} |
| Structure | ${structurePass} | ${total} |
| Fits the kit | ${kitPass} | ${total} |
| Passed the safety checks | ${safetyPass} | ${total} |
| Language | ${languagePass} | ${total} |
| All four checks | ${allPass} | ${total} |

Safety edits recorded across the plans: ${safetyEdits}.
Kit adjustments recorded: ${rows.reduce((sum, row) => sum + row.kitEdits, 0)}.

The offline planner already rotates stations, so kit adjustments stay at zero unless a block claims every player has a racket. The safety filter still adds water, heat, spacing, and age rules after the plan is written. Those edits are counted above.

## Safety edits by code

${changeLines}

## Failures

${failureLines}

## Scenarios

${table}
`;

const outputPath = resolve(process.cwd(), "EVAL.md");
writeFileSync(outputPath, markdown);
console.log(
  `Wrote ${outputPath}: ${kitPass}/${total} fit the kit, ${safetyPass}/${total} passed safety, ${failures.length} failures.`,
);
if (failures.length > 0) {
  process.exitCode = 1;
}
